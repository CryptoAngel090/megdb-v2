#!/usr/bin/env node
// scripts/generate-manifest.js
// Generates a small CODE_INDEX.md manifest based on git-tracked files.
// Usage: node scripts/generate-manifest.js > CODE_INDEX.md

const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')

function main() {
  const repoRoot = process.cwd()
  let out
  try {
    out = execSync('git ls-files', { encoding: 'utf8' })
  } catch (e) {
    console.error('Error running git ls-files — make sure this is a git repository.')
    process.exit(1)
  }

  const files = out.split(/\r?\n/).filter(Boolean)

  // Simple heuristic: include files under src/(components|app|pages|lib|styles)
  const patterns = [
    /src\/components\//,
    /src\/app\//,
    /src\/pages\//,
    /src\/lib\//,
    /src\/styles\//,
  ]
  const picked = files.filter((f) => patterns.some((p) => p.test(f)))

  const groups = {}
  for (const f of picked) {
    const m = f.match(/src\/(components|app|pages|lib|styles)\/([^\/]+)/)
    const key = m ? `${m[1]}/${m[2]}` : path.basename(f)
    if (!groups[key]) groups[key] = []
    groups[key].push(f)
  }

  const now = new Date().toISOString()
  const lines = []
  lines.push('# CODE_INDEX — autogenerated')
  lines.push('')
  lines.push(`_generated: ${now}_`)
  lines.push('')

  for (const [key, paths] of Object.entries(groups)) {
    const p = paths[0]
    lines.push(`- ${p}`)
    lines.push(`  role: ${key}`)
    lines.push(`  keys: `)
    lines.push(`  note: `)
    lines.push('')
  }

  lines.push('---')
  lines.push('')
  lines.push('# MANUAL_OVERRIDES (keep custom notes below this line)')
  lines.push('')

  const manualPath = path.join(repoRoot, 'CODE_INDEX.manual.md')
  if (fs.existsSync(manualPath)) {
    const manual = fs.readFileSync(manualPath, 'utf8').trim()
    if (manual) {
      lines.push(manual)
      lines.push('')
    }
  } else {
    lines.push('<!-- Add manual entries to CODE_INDEX.manual.md -->')
    lines.push('')
  }

  process.stdout.write(lines.join('\n'))
}

main()
